export function uiText(key, params = {}) {
  const pack = TEXT[LANG] || TEXT.en;
  const fallback = TEXT.en[key] || key;
  const value = pack[key] || fallback;
  return value.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, paramKey) => (
    Object.prototype.hasOwnProperty.call(params, paramKey) ? String(params[paramKey]) : ""
  ));
}
